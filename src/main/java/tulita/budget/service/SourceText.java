package tulita.budget.service;

import java.util.Locale;

/**
 * Lower-cases source text and maps the Devanagari unit/technology words used by the Amazon India
 * rows onto their Latin equivalents. It never adds a fact; it only makes the same fact searchable.
 */
public final class SourceText {
    private SourceText() { }

    public static String normalize(String raw) {
        if (raw == null || raw.isBlank()) return "";
        String text = raw.toLowerCase(Locale.ROOT)
                .replace("\u200b", "").replace("\u200c", "").replace("\u200d", "")
                .replace("कंप्यूटर", " computer ")
                .replace("कम्प्यूटर", " computer ")
                .replace("एक्सेसरी", " accessory ")
                .replace("सहायक उपकरण", " accessory ")
                .replace("इलेक्ट्रॉनिक्स", " electronics ")
                .replace("इलेक्ट्रॉनिक", " electronic ")
                .replace("ऑफिस", " office ")
                .replace("मोबाइल", " mobile ")
                .replace("ऑडियो", " audio ")
                .replace("जीबी", " gb ")
                .replace("टीबी", " tb ")
                .replace("रैम", " ram ")
                .replace("एसएसडी", " ssd ")
                .replace("एचडीडी", " hdd ")
                .replace("इंच", " inch ")
                .replace("जनरेशन", " gen ")
                .replace("जनरल", " gen ")
                .replace("नवीनीकृत", " renewed ")
                .replace("रीन्यूड", " renewed ")
                .replace("रिन्यूड", " renewed ")
                .replace("लैपटॉप", " laptop ")
                .replace("नोटबुक", " notebook ")
                .replace("कीबोर्ड कवर", " keyboard cover ")
                .replace("कीबोर्ड", " keyboard ")
                .replace("माउस पैड", " mouse pad ")
                .replace("माऊस", " mouse ")
                .replace("माउस", " mouse ")
                .replace("शामिल नहीं", " not included ")
                .replace("क्लीनिंग", " cleaning ")
                .replace("क्लीनर", " cleaner ")
                .replace("क्लीन", " clean ")
                .replace("स्प्रे", " spray ")
                .replace("ग्रिप", " grip ")
                .replace("टेप", " tape ")
                .replace("चाबियाँ", " keys ")
                .replace("कवर", " cover ")
                .replace("केस", " case ")
                .replace("स्किन", " skin ")
                .replace("प्रोटेक्टर", " protector ")
                .replace("स्टैंड", " stand ")
                .replace("कुशन", " cushion ")
                .replace("ईयरपैड", " earpad ")
                .replace("हेडबैंड", " headband ")
                .replace("केबल", " cable ")
                .replace("पैड", " pad ")
                .replace("एडाप्टर", " adapter ")
                .replace("चार्जर", " charger ")
                .replace("बैटरी", " battery ")
                .replace("बैग", " bag ")
                .replace("स्लीव", " sleeve ")
                .replace("टेबल", " table ")
                .replace("लैंप", " lamp ")
                .replace("लॉक", " lock ")
                .replace("हब", " hub ")
                .replace("वेब कैमरा", " webcam ")
                .replace("वेबकैम", " webcam ")
                .replace("गार्ड", " guard ")
                .replace("पेन ड्राइव", " pen drive ")
                .replace("कॉम्बो", " combo ")
                .replace("कम्बो", " combo ")
                .replace("प्रिंटर", " printer ")
                .replace("टोनर", " toner ")
                .replace("मॉनिटर", " monitor ")
                .replace("माइक्रोफ़ोन", " microphone ")
                .replace("माइक्रोफोन", " microphone ")
                .replace("स्पीकर", " speaker ")
                .replace("संगीत", " musical ")
                .replace("पियानो", " piano ")
                .replace("स्टिकर", " sticker ")
                .replace("कीकैप", " keycap ")
                .replace("हेडफ़ोन", " headphone ")
                .replace("हेडफोन", " headphone ")
                .replace("हेडसेट", " headset ")
                .replace("ईयरफ़ोन", " earphone ")
                .replace("ईयरफोन", " earphone ")
                .replace("ईयरबड", " earbud ")
                .replace("ब्लूटूथ", " bluetooth ")
                .replace("वायरलेस", " wireless ")
                .replace("वायर्ड", " wired ")
                .replace("मैकेनिकल", " mechanical ")
                .replace("बैकलिट", " backlit ")
                .replace("गेमिंग", " gaming ")
                .replace("शोर रद्द", " noise cancel ")
                .replace("नेकबैंड", " neckband ")
                .replace("डीपीआई", " dpi ")
                .replace("बटन", " button ")
                .replace("घंटे", " hours ")
                .replace("कुंजी", " key ");
        return text.replaceAll("\\s+", " ").strip();
    }
}
